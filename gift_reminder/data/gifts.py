# Deduplicate by name (curated wins)
def _merge(curated, bulk):
    seen = {g["name"].lower() for g in curated}
    merged = list(curated)
    for g in bulk:
        if g["name"].lower() not in seen:
            seen.add(g["name"].lower())
            merged.append(g)
    return merged

